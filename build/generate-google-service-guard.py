"""Generate a BYOD network fail-safe from Chromium's traffic annotations.

Uses the pinned upstream extractor rather than parsing C++ strings with regex.
Only browser service annotations owned by Google are denied; renderer page,
XHR, fetch, downloads, and user-configured non-Google endpoints are not matched
merely because their URL contains a Google domain. Review the emitted manifest
when updating Chromium. This supplements, not replaces, service entry removal.
"""

import argparse
import importlib
import json
import pathlib
import re
import subprocess
import sys

# Upstream marks some shared clients as Google-owned even though users/admins
# can configure a non-Google destination. Preserve that capability. Also cover
# generic omnibox requests only when directed at the built-in Google service.
MIXED_DESTINATIONS = {
    "update_client", "managed_configuration_loader", "external_policy_fetcher",
    "ntp_image_url_verification", "omnibox_zerosuggest", "omnibox_suggest",
    "omnibox_suggest_deletion", "management_ui_customer_logo",
    "bookmarks_image_fetcher", "autofill_image_fetcher", "captive_portal_service",
}


def annotation_hash(name):
    value = 0
    for byte in name.encode("ascii"):
        value = ((value * 31 + byte) & 0xFFFFFFFF) % 138003713
    return value


def classify(annotations):
    def google(annotation):
        return bool(re.search(r"\bdestination\s*:\s*GOOGLE_OWNED_SERVICE\b", annotation["text"]))

    blocked = set()
    partials = [a for a in annotations if a["kind"] == "Partial"]
    for annotation in annotations:
        kind = annotation["kind"]
        if kind in ("Definition", "Partial", "BranchedCompleting") and google(annotation):
            blocked.add(annotation["id"])
        if kind == "Completing" and google(annotation):
            # CompleteNetworkTrafficAnnotation retains the partial's ID.
            blocked.update(a["id"] for a in partials if a["extra_id"] == annotation["id"])
        if kind == "BranchedCompleting" and any(
            google(a) and a["extra_id"] == annotation["extra_id"] for a in partials
        ):
            # A branched completion uses its own ID, not the partial's ID.
            blocked.add(annotation["id"])
    return blocked


def google_tld_values(source):
    # The same header also defines YOUTUBE_TLD_LIST: do not merge the two.
    macro = source.split("#define GOOGLE_TLD_LIST", 1)[1].split("\n#define", 1)[0]
    macro = macro.split("// clang-format on", 1)[0]
    return re.findall(r'"([a-z.]+)"', macro)


def google_service_domains(root):
    # Keep a generated copy in net: net must not depend on //components/google.
    source = (root / "components/google/core/common/google_tld_list.h").read_text()
    tlds = google_tld_values(source)
    if "com" not in tlds or "co.uk" not in tlds or len(tlds) < 100:
        raise ValueError("Incomplete upstream Google TLD list")
    return sorted({"google." + tld for tld in tlds} | {
        "googleapis.com", "googleusercontent.com", "gstatic.com", "gvt1.com",
        "gvt2.com", "gvt3.com", "ggpht.com", "chrome.com", "chromium.org",
    })


def render_header(blocked, domains):
    header = """// Generated by BYOD build/generate-google-service-guard.py.
// Uses Chromium's reviewed Google-owned service annotations, not website URLs.
// Domain data is derived from Chromium's BSD-licensed google_tld_list.h.
#ifndef NET_TRAFFIC_ANNOTATION_BYOD_GOOGLE_SERVICES_H_
#define NET_TRAFFIC_ANNOTATION_BYOD_GOOGLE_SERVICES_H_

#include <string_view>

#include "net/traffic_annotation/network_traffic_annotation.h"
#include "url/gurl.h"

namespace net {
inline bool IsByodGoogleServiceEndpoint(const GURL& url) {
  static constexpr std::string_view kDomains[] = {
"""
    for domain in domains:
        if not re.fullmatch(r"[a-z0-9.]+", domain):
            raise ValueError(f"Invalid service domain {domain}")
        header += f'      "{domain}",\n'
    header += """  };
  for (std::string_view domain : kDomains) {
    if (url.DomainIs(domain))
      return true;
  }
  return false;
}

inline bool IsByodGoogleServiceTraffic(NetworkTrafficAnnotationTag tag,
                                      const GURL& url) {
  switch (tag.unique_id_hash_code) {
"""
    for name in sorted(blocked - MIXED_DESTINATIONS):
        if not re.fullmatch(r"[A-Za-z0-9_]+", name):
            raise ValueError(f"Invalid annotation ID {name}")
        header += f'    case internal::ComputeAnnotationHash("{name}"):\n'
    header += "      return true;\n"
    for name in sorted(MIXED_DESTINATIONS):
        header += f'    case internal::ComputeAnnotationHash("{name}"):\n'
    header += """      return IsByodGoogleServiceEndpoint(url);
    default:
      return false;
  }
}
}  // namespace net

#endif  // NET_TRAFFIC_ANNOTATION_BYOD_GOOGLE_SERVICES_H_
"""
    return header


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--root", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    parser.add_argument("--manifest", type=pathlib.Path, required=True)
    parser.add_argument("--from-manifest", type=pathlib.Path,
                        help="Reuse the pre-removal annotation corpus; do not scan patched sources")
    args = parser.parse_args()
    root = args.root.resolve()
    domains = google_service_domains(root)
    if args.from_manifest:
        manifest = json.loads(args.from_manifest.read_text(encoding="utf-8"))
        blocked = {a["id"] for a in manifest["blocked"]}
        manifest["google_service_domains"] = domains
        args.output.write_text(render_header(blocked, domains), encoding="utf-8", newline="\n")
        args.manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(json.dumps({"reused_annotation_manifest": True, "blocked_ids": len(blocked),
                          "service_domains": len(domains)}))
        return
    sys.path.insert(0, str(root / "tools/traffic_annotation/scripts"))
    extractor = importlib.import_module("extractor")
    git = "git.bat" if sys.platform == "win32" else "git"
    result = subprocess.run(
        [git, "grep", "-Il", "-e", "TrafficAnnotation", "--", "*.cc", "*.h", "*.mm"],
        cwd=root, check=True, stdout=subprocess.PIPE, encoding="utf-8",
    )
    annotations, failures = [], []
    for name in result.stdout.splitlines():
        path = pathlib.PurePosixPath(name)
        if (any(part in ("test", "tests", "test_data", "testing", "fuzzers") for part in path.parts)
                or re.search(r"(?:^|_)(?:unittest|browsertest|test|fuzzer)s?(?:_|\.)", path.name)
                or name.startswith(("tools/", "net/traffic_annotation/", "third_party/"))):
            continue
        try:
            contents = (root / name).read_text(encoding="utf-8")
            # Upstream extractor mistakes this diagnostic string for a call.
            # Mask only the literal example; still parse real calls in the file.
            if name == "services/network/cors/cors_url_loader_factory.cc":
                contents = contents.replace(
                    '"It is defined as net::DefineNetworkTrafficAnnotation("',
                    '"Traffic annotation lookup: ("',
                )
            parsed = extractor.extract_annotations(pathlib.Path(name), contents)
        except Exception as error:
            failures.append({"path": name, "error": str(error)})
            continue
        for annotation in parsed:
            if annotation.unique_id in ("test", "test_partial", "missing", "undefined", ""):
                continue
            annotations.append({
                "id": annotation.unique_id, "kind": annotation.type_name.value,
                "extra_id": annotation.extra_id, "text": annotation.text,
                "path": name, "line": annotation.line_number,
            })
    if failures:
        raise RuntimeError(json.dumps(failures, indent=2))
    blocked = classify(annotations)
    if len(blocked) < 100 or any(name.startswith("byod_") for name in blocked):
        raise RuntimeError("Unexpected/incomplete Google annotation set")
    hashes = {}
    for annotation in annotations:
        name = annotation["id"]
        value = annotation_hash(name)
        if value in hashes and hashes[value] != name:
            raise RuntimeError(f"Annotation hash collision: {name}, {hashes[value]}")
        hashes[value] = name
    manifest = {
        "source_revision": subprocess.check_output([git, "rev-parse", "HEAD"], cwd=root, text=True).strip(),
        "annotations_reviewed": len(annotations),
        "google_service_domains": domains,
        "blocked": [dict(a, hash=annotation_hash(a["id"]),
                         google_endpoint_only=a["id"] in MIXED_DESTINATIONS)
                    for a in annotations if a["id"] in blocked or a["id"] in MIXED_DESTINATIONS],
    }
    header = render_header(blocked, domains)
    args.output.write_text(header, encoding="utf-8", newline="\n")
    args.manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({"annotations_reviewed": len(annotations), "blocked_ids": len(blocked)}))


if __name__ == "__main__":
    main()
